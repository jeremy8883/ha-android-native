package io.homeassistant.companion.android.dashboard.panels

import io.homeassistant.companion.android.dashboard.navigation.PanelInfo
import io.homeassistant.companion.android.dashboard.navigation.SidebarItem
import io.homeassistant.companion.android.dashboard.strategy.energy.ENERGY_PANEL
import io.homeassistant.companion.android.dashboard.strategy.summary.SUMMARY_PANELS

/**
 * The frontend panels drawn natively beyond the dashboards: to-do lists, the logbook and the history (the
 * frontend's `todo`, `logbook` and `history` panels). Each is a page of its own, not a dashboard.
 */
val NATIVE_PANELS = setOf("todo", "logbook", "history")

/**
 * Whether this panel is shown natively: the home dashboard, Lovelace dashboards, the summary panels (lights,
 * climate, security, maintenance), the energy panel (generated dashboards too) and [NATIVE_PANELS]. A Lovelace
 * dashboard generated by a strategy that isn't ported (such as Map) can't be told apart from its panel alone.
 */
fun PanelInfo.isNative(): Boolean = componentName == HOME_PANEL ||
    componentName == LOVELACE_PANEL ||
    componentName in SUMMARY_PANELS ||
    componentName == ENERGY_PANEL ||
    componentName in NATIVE_PANELS

/** The sidebar's entries split into those shown [native]ly and those that open [elsewhere], each in its order. */
data class SidebarGroups(val native: List<SidebarItem>, val elsewhere: List<SidebarItem>)

/** [this] split by whether each entry's panel in [panels] is shown natively; unknown panels open elsewhere. */
fun List<SidebarItem>.groupedByNative(panels: Map<String, PanelInfo>): SidebarGroups =
    partition { item -> panels[item.urlPath]?.isNative() == true }.let { (native, elsewhere) ->
        SidebarGroups(native, elsewhere)
    }

/** The home dashboard's panel (`/home`). */
const val HOME_PANEL = "home"

private const val LOVELACE_PANEL = "lovelace"
